export function getLocalizedBookPage(page: BookPageItem, lang: string): BookPageItem {
  if (lang === 'en') {
    const enMeta = BOOK_PAGE_EN[page.id];
    if (!enMeta) {
      return {
        ...page,
        chapter: `Chapter ${page.pageNumber}`,
      };
    }
    return {
      ...page,
      title: enMeta.title,
      label: enMeta.label,
      chapter: `Chapter ${page.pageNumber}`,
      desc: enMeta.desc,
      screenTitle: enMeta.screenTitle || page.screenTitle,
    };
  }
  if (lang === 'gu') {
    const guMeta = BOOK_PAGE_GU[page.id];
    const guChapters = [
      'પ્રથમ અધ્યાય', 'દ્વિતીય અધ્યાય', 'તૃતીય અધ્યાય', 'ચતુર્થ અધ્યાય', 'પંચમ અધ્યાય',
      'ષષ્ઠ અધ્યાય', 'સપ્તમ અધ્યાય', 'અષ્ટમ અધ્યાય', 'નવમ અધ્યાય', 'દશમ અધ્યાય',
      'એકાદશ અધ્યાય', 'દ્વાદશ અધ્યાય', 'ત્રયોદશ અધ્યાય', 'ચતુર્દશ અધ્યાય', 'પંચદશ અધ્યાય',
      'ષોડશ અધ્યાય', 'સપ્તદશ અધ્યાય', 'અષ્ટાદશ અધ્યાય', 'एकोનવિંશતિ અધ્યાય', 'વિંશતિ અધ્યાય'
    ];
    const chapterName = guChapters[page.pageNumber - 1] || `અધ્યાય ${page.pageNumber}`;
    if (!guMeta) {
      return {
        ...page,
        chapter: chapterName,
      };
    }
    return {
      ...page,
      title: guMeta.title,
      label: guMeta.label,
      chapter: chapterName,
      desc: guMeta.desc,
      screenTitle: guMeta.screenTitle || page.screenTitle,
    };
  }
  if (lang === 'mr') {
    const mrMeta = BOOK_PAGE_MR[page.id];
    const mrChapters = [
      'प्रथम अध्याय', 'द्वितीय अध्याय', 'तृतीय अध्याय', 'चतुर्थ अध्याय', 'पंचम अध्याय',
      'षष्ठ अध्याय', 'सप्तम अध्याय', 'अष्टम अध्याय', 'नवम अध्याय', 'दशम अध्याय',
      'एकादश अध्याय', 'द्वादश अध्याय', 'त्रयोदश अध्याय', 'चतुर्दश अध्याय', 'पंचदश अध्याय',
      'षोडश अध्याय', 'सप्तदश अध्याय', 'अष्टादश अध्याय', 'एकोनविंशती अध्याय', 'विंशती अध्याय'
    ];
    const chapterName = mrChapters[page.pageNumber - 1] || `अध्याय ${page.pageNumber}`;
    if (!mrMeta) {
      return {
        ...page,
        chapter: chapterName,
      };
    }
    return {
      ...page,
      title: mrMeta.title,
      label: mrMeta.label,
      chapter: chapterName,
      desc: mrMeta.desc,
      screenTitle: mrMeta.screenTitle || page.screenTitle,
    };
  }
  // Regional Indian languages (bn, ta, te, kn, ml, pa, or)
  const regMap = REGIONAL_PAGE_NAMES[lang];
  if (regMap && regMap[page.id]) {
    const meta = regMap[page.id];
    return {
      ...page,
      title: meta.title,
      label: meta.label,
      screenTitle: `${page.screenTitle?.split(' ')[0] || ''} ${meta.label}`.trim(),
    };
  }
  return page;
}

export function getLocalizedBookPages(pages: BookPageItem[], lang: string): BookPageItem[] {
  return pages.map((p) => getLocalizedBookPage(p, lang));
}

